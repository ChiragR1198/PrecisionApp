export function searchChatEmojis(query) {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  if (EMOJI_SEARCH_HINTS[q]) return EMOJI_SEARCH_HINTS[q];
  const exact = getAllChatEmojis().filter((e) => e === query.trim());
  if (exact.length) return exact;
  const partial = getAllChatEmojis().filter((e) => e.includes(query.trim()));
  return partial.length ? partial : [];
}

/** Flat list for search across all categories */
export function getAllChatEmojis() {
  const seen = new Set();
  const out = [];
  CHAT_EMOJI_CATEGORY_IDS.forEach((id) => {
    if (id === 'recent') return;
    const list = CHAT_EMOJI_CATEGORIES[id]?.emojis || [];
    list.forEach((e) => {
      if (!seen.has(e)) {
        seen.add(e);
        out.push(e);
      }
    });
  });
  return out;
}
